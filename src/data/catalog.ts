import type { GameRecord } from '../types'

function htmlGame(
  id: string,
  title: string,
  author: string,
  genres: string[],
  blurb: string,
  description: string,
  folder: string,
  cover: string,
  palette: GameRecord['palette'],
  createdAt: string,
  rating = 0,
): GameRecord {
  return {
    id,
    title,
    author,
    blurb,
    description,
    genres,
    createdAt,
    cover,
    palette,
    house: true,
    bytes: 18_000,
    rating,
    source: { kind: 'html', entry: 'index.html', href: `/games/${folder}/index.html` },
  }
}

